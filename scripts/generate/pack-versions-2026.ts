// Writes scripts/migrations/015_country_packs_2026.sql from the built-in pack
// data (src/data/countries.ts + country-law-2026*.ts). Re-run after changing
// that data:  npx tsx scripts/generate/pack-versions-2026.ts
import { writeFileSync } from 'fs';
import { packConfig2026 } from '../../src/data/packConfig';
import { packFor2026, allCountryLaw2026 } from '../../src/data/country-law-2026';

const CODES = ['SG', 'MY', 'ID', 'TH', 'PH', 'VN', 'HK', 'TW', 'JP', 'KR', 'CN', 'US', 'GB', 'AU', 'DE', 'FR',
  'IN', 'NZ', 'CA', 'AE', 'NL', 'IE', 'CH', 'ES', 'IT', 'SA', 'BR', 'MX'];

const TAG = '$' + 'pack' + '$';
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const law = allCountryLaw2026();
const profiles: string[] = [];
const versions: string[] = [];
for (const code of CODES) {
  const p = packFor2026(code);
  const config = packConfig2026(code);
  if (!p || !config) throw new Error(`No pack data for ${code}`);
  profiles.push(`  (${q(code)}, ${q(p.general.name)}, ${q(p.general.currency)}, ${q(p.general.phone_code)})`);
  const json = JSON.stringify(config);
  if (json.includes(TAG)) throw new Error('config contains the dollar-quote tag');
  versions.push(`  (${q(code)}, '2026', ${q(law[code]?.effective_from ?? '2026-01-01')}, ${TAG}${json}${TAG}::jsonb)`);
}

const sql = `-- 015_country_packs_2026.sql — version "2026" of every country pack with
-- current law (minimum wages, social security, income tax, leave minimums),
-- researched November 2026. GENERATED by scripts/generate/pack-versions-2026.ts
-- from src/data/countries.ts and src/data/country-law-2026*.ts — edit those
-- and regenerate rather than editing this file.
--
-- Adds the new countries to country_profiles, allows the 'calendar_days'
-- leave counting method, and inserts each 2026 version. An existing 2026
-- version is only replaced when it is an empty placeholder, so edits made on
-- the Country Packs page are kept. Idempotent.

INSERT INTO country_profiles (code, name, currency, phone_code) VALUES
${profiles.join(',\n')}
ON CONFLICT (code) DO NOTHING;

ALTER TABLE leave_types DROP CONSTRAINT IF EXISTS leave_types_count_method_check;
ALTER TABLE leave_types ADD CONSTRAINT leave_types_count_method_check
  CHECK (count_method IN ('working_days', 'weeks', 'calendar_days'));

INSERT INTO country_pack_versions (country_code, version, effective_from, is_active, config)
SELECT v.country_code, v.version, v.effective_from::date, true, v.config
FROM (VALUES
${versions.join(',\n')}
) AS v(country_code, version, effective_from, config)
ON CONFLICT (country_code, version) DO UPDATE
  SET config = EXCLUDED.config, effective_from = EXCLUDED.effective_from
  WHERE country_pack_versions.config IS NULL OR country_pack_versions.config = '{}'::jsonb;

SELECT 'migration 015 complete' AS status,
       (SELECT count(DISTINCT country_code) FROM country_pack_versions WHERE version = '2026') AS countries_with_2026_pack;
`;
writeFileSync(new URL('../migrations/015_country_packs_2026.sql', import.meta.url), sql);
console.log(`wrote ${CODES.length} countries`);
